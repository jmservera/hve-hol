def _is_text(value: str) -> bool:
    return bool(
        value
        and value not in _LITERALS
        and not value.isdecimal()
        and not value.startswith(("https://", "http://"))
        and not re.fullmatch(r"[a-z0-9-]+\.html(?:#[a-z0-9-]+)?", value)
        and not re.fullmatch(r"\d{2}:\d{2}–\d{2}:\d{2}", value)
    )


def _texts(value: object) -> Iterator[str]:
    if isinstance(value, dict):
        for key, child in value.items():
            if key not in _STRUCTURAL_FIELDS:
                yield from _texts(child)
    elif isinstance(value, (list, tuple)):
        for child in value:
            yield from _texts(child)
    elif isinstance(value, str) and _is_text(value):
        yield value


def _add(label: str, original: object, translated: list[str]) -> None:
    pending = list(dict.fromkeys(text for text in _texts(original) if text not in _TRANSLATIONS))
    if len(pending) != len(translated):
        raise ValueError(
            f"{label}: se esperaban {len(pending)} traducciones y hay {len(translated)}. "
            "Revisa todos los textos del apartado y su orden."
        )
    _TRANSLATIONS.update(zip(pending, translated, strict=True))


def _clone(value: object) -> object:
    if isinstance(value, dict):
        return {
            key: deepcopy(child) if key in _STRUCTURAL_FIELDS else _clone(child)
            for key, child in value.items()
        }
    if isinstance(value, list):
        return [_clone(child) for child in value]
    if isinstance(value, tuple):
        return tuple(_clone(child) for child in value)
    if isinstance(value, str) and _is_text(value):
        if value not in _TRANSLATIONS:
            raise ValueError(f"Falta la traducción española de {value!r}. Añádela antes de publicar.")
        return _TRANSLATIONS[value]
    return value


